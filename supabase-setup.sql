create table if not exists public.site_submissions (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('contact', 'order', 'notification', 'ai_guide', 'interest', 'note')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_content (
  id text primary key,
  type text not null,
  title text not null,
  url text not null default '',
  status text not null default 'draft',
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchased_update_access (
  id bigint generated by default as identity primary key,
  email text not null,
  purchaser_name text not null default '',
  license_code text not null default '',
  purchased_at date not null default current_date,
  expires_at date not null,
  device_limit integer not null default 2,
  devices jsonb not null default '[]'::jsonb,
  status text not null default 'active' check (status in ('active', 'blocked', 'refunded')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

