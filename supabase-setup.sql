create or replace function public.check_full_update_access(p_email text)
returns table (
  is_active boolean,
  purchased_at date,
  expires_at date,
  days_left integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    coalesce(bool_or(
      status = 'active'
      and expires_at >= current_date
    ), false) as is_active,
    max(purchased_at) as purchased_at,
    max(expires_at) as expires_at,
    greatest(coalesce(max(expires_at) - current_date, -1), -1)::integer as days_left
  from public.purchased_update_access
  where lower(trim(email)) = lower(trim(p_email));
$$;

revoke all on function public.check_full_update_access(text) from public;
grant execute on function public.check_full_update_access(text) to anon, authenticated;

create or replace function public.activate_full_license(
  p_email text,
  p_license_code text,
  p_device_id text,
  p_device_name text default '',
  p_app_version text default ''
)
returns table (
  is_active boolean,
  expires_at date,
  days_left integer,
  device_count integer,
  device_limit integer,
  message text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  row_data public.purchased_update_access%rowtype;
  normalized_email text := lower(trim(coalesce(p_email, '')));
  clean_code text := trim(coalesce(p_license_code, ''));
  clean_device text := trim(coalesce(p_device_id, ''));
  next_devices jsonb;
  existing_device boolean;
begin
  if normalized_email = '' or clean_code = '' or clean_device = '' then
    return query select false, null::date, -1, 0, 2, 'missing_details';
    return;
  end if;

  select * into row_data
  from public.purchased_update_access
  where email = normalized_email
    and license_code = clean_code
  limit 1;

  if not found then
    return query select false, null::date, -1, 0, 2, 'not_found';
    return;
  end if;

  if row_data.status <> 'active' or row_data.expires_at < current_date then
    return query select false, row_data.expires_at, greatest(row_data.expires_at - current_date, -1)::integer,
      jsonb_array_length(row_data.devices), row_data.device_limit, 'inactive';
    return;
  end if;

  existing_device := row_data.devices @> jsonb_build_array(jsonb_build_object('id', clean_device));
  if not existing_device and jsonb_array_length(row_data.devices) >= row_data.device_limit then
    return query select false, row_data.expires_at, greatest(row_data.expires_at - current_date, -1)::integer,
      jsonb_array_length(row_data.devices), row_data.device_limit, 'device_limit';
    return;
  end if;

  if existing_device then
    next_devices := (
      select jsonb_agg(
        case
          when device->>'id' = clean_device then
            device || jsonb_build_object('last_seen_at', now(), 'app_version', p_app_version)
          else device
        end
      )
      from jsonb_array_elements(row_data.devices) device
    );
  else
    next_devices := row_data.devices || jsonb_build_array(jsonb_build_object(
      'id', clean_device,
      'name', left(coalesce(p_device_name, ''), 80),
      'first_seen_at', now(),
      'last_seen_at', now(),
      'app_version', left(coalesce(p_app_version, ''), 40)
    ));
  end if;

  update public.purchased_update_access
  set devices = coalesce(next_devices, '[]'::jsonb),
      updated_at = now()
  where id = row_data.id;

  return query select true, row_data.expires_at, greatest(row_data.expires_at - current_date, -1)::integer,
    jsonb_array_length(coalesce(next_devices, '[]'::jsonb)), row_data.device_limit, 'active';
end;
$$;

revoke all on function public.activate_full_license(text, text, text, text, text) from public;
